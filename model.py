#!/usr/bin/env python3
"""The SysML v2 governance model is the source: `model/governance.sysml` is hand-written (kinds with the tier calc,
the `Repository` facts, one requirement def per registry check in a package per policy, named after their IDs in
PascalCase). This module only derives what follows from data: `model/repositories.sysml` from repos.yaml (one part
per entry and one `satisfy` assertion per registry check), and reads the model back through OpenSysML: which
assertions are in effect (each requirement's `inEffect` assumption, evaluated for the repository), the tier, the
patterns the sensors apply, and the declared facts (the API's JSON element form).
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys
import warnings

import opensysml
import yaml

from common import CHECK_APPLIES, Registry

MODEL = pathlib.Path("model/governance.sysml")


def pascal(s: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in s.replace("_", "-").split("-"))


def attested_fact(check_id: str) -> str:
    return "attested" + pascal(check_id)


def evidence_fact(check_id: str) -> str:
    return f"evidence{pascal(check_id)}Resolves"


def kind_ref(attr: str, value: str) -> str:
    return f"{attr.capitalize()}::{value}"


def applies_expr(rule) -> str:
    """The registry's applies_if as the SysML expression the model's `assume constraint inEffect` must state
    (the unit tests compare the two; nothing at run time evaluates the registry's rule)."""
    if rule is None:
        return "true"
    if "all" in rule:
        return " and ".join(f"({applies_expr(r)})" for r in rule["all"])
    if "any" in rule:
        return " or ".join(f"({applies_expr(r)})" for r in rule["any"])
    if "not" in rule:
        return f"not ({applies_expr(rule['not'])})"
    attr = rule["attr"]
    if "eq" in rule:
        return f"repo.{attr} == {kind_ref(attr, rule['eq'])}"
    if "in" in rule:
        return " or ".join(f"repo.{attr} == {kind_ref(attr, v)}" for v in rule["in"])
    raise SystemExit(f"construction error: unsupported applies_if clause {rule}")


def check_rule(policy: dict, check: dict):
    rules = [r for r in (policy.get("applies_if"), CHECK_APPLIES.get(check["id"])) if r]
    return {"all": rules} if len(rules) > 1 else (rules[0] if rules else None)


def repo_policies(registry: Registry):
    return [p for p in registry.policies if p.get("scope", "repository") == "repository"]


def requirement_name(policy_id: str, check_id: str) -> str:
    return f"Governance::Policies::{pascal(policy_id)}::{pascal(check_id)}"


def checks(registry: Registry):
    """(policy, check, kind) for every repository-scope check the registry defines."""
    return [(p, c, kind) for p in repo_policies(registry) for kind in ("automated", "attested") for c in p["checks"].get(kind) or []]


def element(name: str) -> str:
    return f"Repositories::'{name}'"


def assertion(name: str, check_id: str) -> str:
    return f"'{name}: {check_id}'"


def repositories_sysml(registry: Registry, entries: list[dict]) -> str:
    out = ["package Repositories {\n",
           "    doc /* Generated by model.py from repos.yaml; the facts are imported at run time (sense.py). */\n",
           "    private import Governance::*;\n\n"]
    for e in entries:
        if e["stage"] not in registry.kinds.get(e["type"], {}):
            raise SystemExit(f"construction error: no kind {e['type']}/{e['stage']} in kinds.yaml")
        out.append(f"    part '{e['name']}' : Repository {{\n")
        out.append(f"        attribute :>> type = Type::{e['type']};\n        attribute :>> stage = Stage::{e['stage']};\n")
        attest = e.get("attest") or {}
        for p, c, kind in checks(registry):
            if kind == "attested":
                out.append(f"        attribute :>> {attested_fact(c['id'])} = {'true' if c['id'] in attest else 'false'};\n")
        out.append("    }\n")
        for p, c, kind in checks(registry):
            out.append(f"    satisfy requirement {assertion(e['name'], c['id'])} : {requirement_name(p['id'], c['id'])[len('Governance::'):]} by '{e['name']}';\n")
        out.append("\n")
    out.append("}\n")
    return "".join(out)


def generate(registry: Registry, config: dict, out_dir: pathlib.Path) -> pathlib.Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "repositories.sysml"
    path.write_text(repositories_sysml(registry, config["repos"]))
    return path


def source(model_dir: pathlib.Path) -> str:
    """The hand-written model and the generated repositories as one document (import_data binds values in one)."""
    return MODEL.read_text() + "\n" + (model_dir / "repositories.sysml").read_text()


class Applicability:
    """Which assertions are in effect and each repository's tier, as OpenSysML evaluates them in the model: the
    assertion's `inEffect` assumption for its repository, and the repository's `tier`."""

    def __init__(self, conn: opensysml.Connection, model_dir: pathlib.Path, registry: Registry, entries: list[dict]):
        try:
            parsed = conn.parse_sources([("model.sysml", source(model_dir))], strict=True)
            self.effective = {(e["name"], c["id"]): self._value(parsed, f"Repositories::{assertion(e['name'], c['id'])}.inEffect")
                              for e in entries for _, c, _ in checks(registry)}
            self.tiers = {e["name"]: self._value(parsed, f"{element(e['name'])}.tier").literal_id.rsplit("::", 1)[1] for e in entries}
        except opensysml.errors.OpenSysMLError as e:
            raise SystemExit(f"construction error: OpenSysML could not evaluate which checks are in effect: {e}")

    @staticmethod
    def _value(parsed, expression: str):
        value = parsed.eval(expression)
        value = value[0] if isinstance(value, list) and len(value) == 1 else value
        if not isinstance(value, (bool, opensysml.EnumLiteral)):
            raise SystemExit(f"construction error: {expression} evaluated to {value!r}")
        return value

    def in_effect(self, registry: Registry, entry: dict):
        """(policy, check, kind) for every check the model says is in effect for the entry."""
        return [(p, c, kind) for p, c, kind in checks(registry) if self.effective[(entry["name"], c["id"])]]

    def tier(self, entry: dict) -> str:
        return self.tiers[entry["name"]]


class Model:
    """What the hand-written model declares, read through OpenSysML's own parser as the API's JSON element form."""

    def __init__(self, conn: opensysml.Connection, path: pathlib.Path = MODEL):
        try:
            parsed = conn.parse_sources([(str(path), path.read_text())], strict=True)
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", opensysml.ExperimentalFeatureWarning)
                elements = json.loads(str(parsed.to_api_json()))
        except opensysml.errors.OpenSysMLError as e:
            raise SystemExit(f"construction error: OpenSysML could not read {path}: {e}")
        by_id = {e["@id"]: e for e in elements if "@id" in e}
        try:
            self.semver = re.compile(self._strings(parsed, "Governance::Patterns::semverTag")[0])
            self.sbom_globs = self._strings(parsed, "Governance::Patterns::sbomAsset")
        except (opensysml.errors.OpenSysMLError, re.error) as e:
            raise SystemExit(f"construction error: the model's patterns could not be read: {e}")
        self.facts: dict[str, str] = {}
        for e in elements:
            q = e.get("qualifiedName") or ""
            if e.get("@type") == "AttributeUsage" and q.startswith("Governance::Repository::"):
                types = [by_id.get(t.get("@id"), {}).get("declaredName") for t in e.get("type") or []]
                self.facts[e["declaredName"]] = types[0] if types else None
        self.requirements = sorted(e["qualifiedName"] for e in elements
                                   if e.get("@type") == "RequirementDefinition" and e.get("qualifiedName", "").startswith("Governance::Policies::"))


    @staticmethod
    def _strings(parsed, expression: str) -> list[str]:
        value = parsed.eval(expression)
        value = value if isinstance(value, list) else [value]
        if not value or not all(isinstance(v, str) for v in value):
            raise SystemExit(f"construction error: {expression} evaluated to {value!r}")
        return value


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="repos.yaml")
    ap.add_argument("--registry", required=True, help="path to a checkout of Open-MBEE/repo-registry at the pinned ref")
    ap.add_argument("--out", default="model")
    ap.add_argument("--check", action="store_true", help="fail if repositories.sysml under --out is not what repos.yaml gives")
    args = ap.parse_args(argv)
    config = yaml.safe_load(pathlib.Path(args.config).read_text())
    registry = Registry(pathlib.Path(args.registry))
    out = pathlib.Path(args.out) / "repositories.sysml"
    text = repositories_sysml(registry, config["repos"])
    if args.check:
        if not out.exists() or out.read_text() != text:
            print(f"stale: {out} (run model.py to regenerate)", file=sys.stderr)
            return 1
        print("repositories.sysml up to date")
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
